func GetDailyConsumptionData(startTime int64, endTime int64, username string, userId int) ([]*DailyConsumptionData, error) {
	_, offset := time.Now().In(time.Local).Zone()
	bucketExpr := dailyConsumptionBucketExpr(offset)
	selectSQL := fmt.Sprintf(`%s AS bucket,
		COALESCE(SUM(CASE WHEN status = '%s' THEN -quota ELSE quota END), 0) AS quota,
		COALESCE(SUM(CASE WHEN status = '%s' THEN 0 ELSE 1 END), 0) AS request_count,
		COALESCE(SUM(COALESCE(prompt_tokens, 0)), 0) AS prompt_tokens,
		COALESCE(SUM(COALESCE(completion_tokens, 0)), 0) AS completion_tokens,
		COALESCE(SUM(COALESCE(prompt_tokens, 0) + COALESCE(completion_tokens, 0)), 0) AS total_tokens`,
		bucketExpr,
		BillingLedgerStatusRefunded,
		BillingLedgerStatusRefunded,
	)

	type dailyRow struct {
		Bucket           int64
		Quota            int64
		RequestCount     int64
		PromptTokens     int64
		CompletionTokens int64
		TotalTokens      int64
	}
	var rows []dailyRow
	query := DB.Table("billing_ledger").
		Select(selectSQL).
		Where("status IN ?", []string{BillingLedgerStatusSettled, BillingLedgerStatusRefunded})
	if startTime > 0 {
		query = query.Where("created_at >= ?", startTime)
	}
	if endTime > 0 {
		query = query.Where("created_at <= ?", endTime)
	}
	if username != "" {
		query = query.Where("username = ?", username)
	}
	if userId > 0 {
		query = query.Where("user_id = ?", userId)
	}
	if err := query.Group(bucketExpr).Order("bucket ASC").Scan(&rows).Error; err != nil {
		return nil, err
	}

	result := make([]*DailyConsumptionData, 0, len(rows))
	for _, row := range rows {
		result = append(result, &DailyConsumptionData{
			Date:             time.Unix(row.Bucket, 0).Local().Format("2006-01-02"),
			CreatedAt:        row.Bucket,
			Quota:            row.Quota,
			RequestCount:     row.RequestCount,
			PromptTokens:     row.PromptTokens,
			CompletionTokens: row.CompletionTokens,
			TotalTokens:      row.TotalTokens,
		})
	}
	return result, nil
}

func dailyConsumptionBucketExpr(offset int) string {
	if common.UsingMySQL {
		return fmt.Sprintf("FLOOR((created_at + %d) / 86400) * 86400 - %d", offset, offset)
	}
	return fmt.Sprintf("((created_at + %d) / 86400) * 86400 - %d", offset, offset)
}
